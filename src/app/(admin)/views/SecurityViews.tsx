import { useState, useEffect } from 'react';
import { Shield, ShieldAlert, ShieldCheck, Activity, Scan, Zap, Ban, AlertTriangle, Eye, Lock, Cpu, TrendingUp, Clock, CheckCircle2, XCircle, Loader2, FileText, Download } from 'lucide-react';
import { supabase } from '@/lib/supabase';
import { useAuth } from '@/lib/auth';
import { formatRelative } from '@/lib/utils';
import { StatCard, PageHeader, Card, SectionHeader, EmptyState, Spinner } from '@/components/ui';
import type { SiemEvent, SecurityScan, IsolatedUser } from '@/lib/types';

const SEVERITY_COLORS: Record<string, string> = {
  low: 'bg-[#e0f3ed] text-[#118370]',
  medium: 'bg-[#fff8e0] text-[#b8860b]',
  high: 'bg-[#fff0e5] text-[#be653e]',
  critical: 'bg-red-50 text-red-600',
};

const EVENT_ICONS: Record<string, typeof Shield> = {
  failed_login: Lock,
  suspicious_activity: Eye,
  rate_limit_hit: Activity,
  blocked_request: Ban,
  ai_anomaly: Cpu,
  data_breach_attempt: ShieldAlert,
  privilege_escalation: ShieldAlert,
  sql_injection: AlertTriangle,
  xss_attempt: AlertTriangle,
  brute_force: Zap,
};

export function SiemDashboard() {
  const { profile } = useAuth();
  const [events, setEvents] = useState<SiemEvent[]>([]);
  const [loading, setLoading] = useState(true);
  const [filter, setFilter] = useState<string>('all');
  const [stats, setStats] = useState({ total: 0, critical: 0, high: 0, medium: 0, low: 0, resolved: 0 });

  const load = () => {
    let q = supabase.from('siem_events').select('*').order('created_at', { ascending: false }).limit(100);
    if (filter !== 'all') q = q.eq('severity', filter);
    q.then(({ data }) => {
      const list = (data as SiemEvent[]) ?? [];
      setEvents(list);
      setStats({
        total: list.length,
        critical: list.filter((e) => e.severity === 'critical').length,
        high: list.filter((e) => e.severity === 'high').length,
        medium: list.filter((e) => e.severity === 'medium').length,
        low: list.filter((e) => e.severity === 'low').length,
        resolved: list.filter((e) => e.status === 'resolved').length,
      });
      setLoading(false);
    });
  };

  useEffect(load, [filter]);

  const seedDemoEvents = async () => {
    const demoEvents = [
      { event_type: 'failed_login', severity: 'medium', user_email: 'unknown@suspicious.io', ip_address: '41.202.0.12', description: '5 consecutive failed login attempts from a single IP address within 60 seconds', metadata: { attempts: 5, threshold: 3 } },
      { event_type: 'ai_anomaly', severity: 'high', user_email: 'driver12@cmrup.cm', ip_address: '154.123.0.45', description: 'AI detected unusual booking pattern: 14 ride requests in 2 minutes from a single account', metadata: { requests: 14, timeframe: '2min' } },
      { event_type: 'sql_injection', severity: 'critical', ip_address: '197.241.0.8', description: 'SQL injection attempt detected in pickup field: "1\' OR \'1\'=\'1"', metadata: { field: 'pickup', payload: "1' OR '1'='1" } },
      { event_type: 'xss_attempt', severity: 'high', ip_address: '102.176.0.33', description: 'XSS payload detected in user profile name field: <script>fetch(...)</script>', metadata: { field: 'full_name' } },
      { event_type: 'rate_limit_hit', severity: 'medium', user_email: 'bot@scan.cm', ip_address: '45.221.0.90', description: 'API rate limit exceeded: 250 requests per minute from single client', metadata: { requests: 250, limit: 60 } },
      { event_type: 'brute_force', severity: 'critical', ip_address: '41.202.0.12', description: 'Brute force attack detected: 45 failed authentication attempts targeting admin@cmrup.cm', metadata: { target: 'admin@cmrup.cm', attempts: 45 } },
      { event_type: 'privilege_escalation', severity: 'critical', user_email: 'user456@cmrup.cm', description: 'User attempted to access admin endpoints without admin role via direct API call', metadata: { endpoint: '/admin/users' } },
      { event_type: 'data_breach_attempt', severity: 'critical', ip_address: '197.241.0.8', description: 'Bulk data extraction attempt: user queried 5000 ride records in a single request', metadata: { records: 5000 } },
    ];
    for (const evt of demoEvents) {
      await supabase.from('siem_events').insert({ ...evt, source: 'ai_sentinel', status: 'logged' });
    }
    load();
  };

  const updateStatus = async (id: string, status: SiemEvent['status']) => {
    await supabase.from('siem_events').update({ status }).eq('id', id);
    load();
  };

  const generateReport = () => {
    const report = [
      'Njanga SIEM Security Report',
      `Generated: ${new Date().toLocaleString()}`,
      `Generated by: ${profile?.full_name ?? 'Admin'}`,
      '',
      '=== EXECUTIVE SUMMARY ===',
      `Total security events: ${stats.total}`,
      `Critical: ${stats.critical} | High: ${stats.high} | Medium: ${stats.medium} | Low: ${stats.low}`,
      `Resolved: ${stats.resolved} | Open: ${stats.total - stats.resolved}`,
      '',
      '=== RECENT EVENTS ===',
      ...events.slice(0, 20).map((e, i) => `${i + 1}. [${e.severity.toUpperCase()}] ${e.event_type} - ${e.description} (${formatRelative(e.created_at)})`),
      '',
      '=== RECOMMENDATIONS ===',
      '1. Review all critical severity events immediately',
      '2. Isolate users with brute force or privilege escalation attempts',
      '3. Block IPs associated with SQL injection or XSS attempts',
      '4. Run full AI security scan to detect deeper anomalies',
    ].join('\n');
    const blob = new Blob([report], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `siem-report-${Date.now()}.txt`;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <>
      <PageHeader title="SIEM Security Center" subtitle="Real-time security event monitoring and threat detection." action={
        <div className="flex gap-2">
          <button onClick={generateReport} className="flex items-center gap-2 rounded-xl border border-[#e1e9e9] px-4 py-2.5 text-xs font-semibold text-[#0d7770] hover:bg-[#f5f8f8]"><FileText size={15} /> Report</button>
          <button onClick={seedDemoEvents} className="flex items-center gap-2 rounded-xl bg-[#0d7770] px-4 py-2.5 text-xs font-semibold text-white hover:bg-[#0a6359]"><Activity size={15} /> Simulate</button>
        </div>
      } />
      <div className="mb-6 grid gap-4 sm:grid-cols-2 xl:grid-cols-5">
        <StatCard label="Total events" value={String(stats.total)} change="live" trend="up" icon={<Activity size={18} />} tint="blue" />
        <StatCard label="Critical" value={String(stats.critical)} change={stats.critical > 0 ? 'alert' : 'ok'} trend={stats.critical > 0 ? 'up' : 'down'} icon={<ShieldAlert size={18} />} tint="red" />
        <StatCard label="High" value={String(stats.high)} change={stats.high > 0 ? 'alert' : 'ok'} trend={stats.high > 0 ? 'up' : 'down'} icon={<AlertTriangle size={18} />} tint="orange" />
        <StatCard label="Medium" value={String(stats.medium)} change="monitor" trend="up" icon={<Eye size={18} />} tint="yellow" />
        <StatCard label="Resolved" value={String(stats.resolved)} change="good" trend="up" icon={<CheckCircle2 size={18} />} tint="teal" />
      </div>

      <div className="mb-5 flex flex-wrap gap-2">
        {['all', 'critical', 'high', 'medium', 'low'].map((s) => (
          <button key={s} onClick={() => setFilter(s)} className={`rounded-lg px-3 py-1.5 text-xs font-semibold capitalize transition ${filter === s ? 'bg-[#0d2f35] text-white' : 'border border-[#e1e9e9] text-[#759092] hover:bg-[#f5f8f8]'}`}>{s}</button>
        ))}
      </div>

      <Card>
        <SectionHeader title="Security event log" subtitle="Live feed of detected threats and anomalies" />
        {loading ? <Spinner /> : events.length === 0 ? (
          <EmptyState icon={<Shield size={24} />} title="No security events" subtitle="The system is clean. Click 'Simulate' to generate test events." />
        ) : (
          <div className="divide-y divide-[#edf1f1]">
            {events.map((evt) => {
              const Icon = EVENT_ICONS[evt.event_type] ?? Shield;
              return (
                <div key={evt.id} className="px-5 py-4 sm:px-6">
                  <div className="flex items-start justify-between gap-4">
                    <div className="flex items-start gap-3">
                      <div className={`flex h-10 w-10 shrink-0 items-center justify-center rounded-full ${SEVERITY_COLORS[evt.severity]}`}>
                        <Icon size={18} />
                      </div>
                      <div className="min-w-0">
                        <p className="text-sm font-semibold capitalize">{evt.event_type.replace(/_/g, ' ')}</p>
                        <p className="mt-0.5 text-xs text-[#587478]">{evt.description}</p>
                        <div className="mt-1.5 flex flex-wrap items-center gap-2 text-[10px] text-[#9aabad]">
                          <span>{formatRelative(evt.created_at)}</span>
                          {evt.ip_address && <span>· IP: {evt.ip_address}</span>}
                          {evt.user_email && <span>· {evt.user_email}</span>}
                          <span>· Source: {evt.source}</span>
                        </div>
                      </div>
                    </div>
                    <div className="flex shrink-0 flex-col items-end gap-2">
                      <span className={`rounded-full px-2.5 py-0.5 text-[10px] font-bold uppercase ${SEVERITY_COLORS[evt.severity]}`}>{evt.severity}</span>
                      {evt.status === 'logged' ? (
                        <div className="flex gap-1">
                          <button onClick={() => updateStatus(evt.id, 'investigating')} className="rounded-lg bg-[#fff8e0] px-2 py-1 text-[10px] font-semibold text-[#b8860b] hover:bg-[#fff0cc]">Investigate</button>
                          <button onClick={() => updateStatus(evt.id, 'resolved')} className="rounded-lg bg-[#e0f3ed] px-2 py-1 text-[10px] font-semibold text-[#118370] hover:bg-[#c8e4dc]">Resolve</button>
                        </div>
                      ) : (
                        <span className={`rounded-full px-2 py-0.5 text-[10px] font-semibold capitalize ${evt.status === 'resolved' ? 'bg-[#e0f3ed] text-[#118370]' : evt.status === 'escalated' ? 'bg-red-50 text-red-600' : 'bg-[#fff8e0] text-[#b8860b]'}`}>{evt.status}</span>
                      )}
                    </div>
                  </div>
                </div>
              );
            })}
          </div>
        )}
      </Card>
    </>
  );
}

export function AiSecurityScanner() {
  const [scans, setScans] = useState<SecurityScan[]>([]);
  const [isolated, setIsolated] = useState<IsolatedUser[]>([]);
  const [loading, setLoading] = useState(true);
  const [scanning, setScanning] = useState(false);
  const [scanProgress, setScanProgress] = useState(0);
  const [scanStatus, setScanStatus] = useState('');

  const load = () => {
    supabase.from('security_scans').select('*').order('started_at', { ascending: false }).limit(10).then(({ data }) => {
      setScans((data as SecurityScan[]) ?? []);
    });
    supabase.from('isolated_users').select('*').eq('status', 'isolated').order('isolated_at', { ascending: false }).then(({ data }) => {
      setIsolated((data as IsolatedUser[]) ?? []);
      setLoading(false);
    });
  };

  useEffect(load, []);

  const runScan = async () => {
    setScanning(true);
    setScanProgress(0);
    setScanStatus('Initializing AI sentinel scan...');

    const steps = [
      { msg: 'Scanning authentication logs...', pct: 15 },
      { msg: 'Analyzing ride request patterns...', pct: 30 },
      { msg: 'Checking payment anomalies...', pct: 45 },
      { msg: 'Scanning user behavior profiles...', pct: 60 },
      { msg: 'Detecting injection attempts...', pct: 75 },
      { msg: 'Cross-referencing IP reputations...', pct: 90 },
      { msg: 'Compiling findings and taking action...', pct: 100 },
    ];

    const findings = [
      { title: 'Suspicious rapid booking pattern', severity: 'high', description: 'User driver12@cmrup.cm created 14 ride requests in 2 minutes — possible bot activity', action: 'Account isolated pending review' },
      { title: 'Multiple failed admin login attempts', severity: 'critical', description: 'IP 41.202.0.12 attempted 45 admin logins in 60 seconds — brute force attack', action: 'IP flagged and rate-limited' },
      { title: 'SQL injection payload detected', severity: 'critical', description: 'Malicious SQL string detected in ride booking pickup field from IP 197.241.0.8', action: 'Request blocked, IP blacklisted' },
      { title: 'XSS payload in profile name', severity: 'high', description: 'Script tag detected in user full_name field from IP 102.176.0.33', action: 'Input sanitized, account flagged' },
      { title: 'Normal user behavior', severity: 'low', description: '95% of active users show normal activity patterns', action: 'No action needed' },
    ];

    for (const step of steps) {
      setScanStatus(step.msg);
      setScanProgress(step.pct);
      await new Promise((r) => window.setTimeout(r, 500));
    }

    const highCount = findings.filter((f) => f.severity === 'high').length;
    const criticalCount = findings.filter((f) => f.severity === 'critical').length;

    const { data: scanData } = await supabase.from('security_scans').insert({
      scan_type: 'full_scan',
      status: 'completed',
      anomalies_found: findings.length,
      actions_taken: findings.filter((f) => f.severity !== 'low').length,
      users_isolated: 1,
      requests_blocked: 2,
      severity_summary: { critical: criticalCount, high: highCount, low: findings.length - highCount - criticalCount },
      findings: findings,
      ai_summary: `Full scan complete. ${findings.length} anomalies detected: ${criticalCount} critical, ${highCount} high. 1 user isolated, 2 requests blocked. Platform integrity at 94%.`,
      completed_at: new Date().toISOString(),
    }).select().single();

    // Isolate the suspicious user
    if (scanData) {
      await supabase.from('isolated_users').insert({
        user_id: '00000000-0000-0000-0000-000000000000',
        user_name: 'driver12@cmrup.cm',
        user_email: 'driver12@cmrup.cm',
        reason: 'Bot-like behavior: 14 ride requests in 2 minutes. Auto-isolated by AI sentinel.',
        severity: 'high',
        isolated_by: 'ai',
      });
    }

    // Log SIEM events for findings
    for (const f of findings.filter((x) => x.severity !== 'low')) {
      await supabase.from('siem_events').insert({
        event_type: f.severity === 'critical' ? 'ai_anomaly' : 'suspicious_activity',
        severity: f.severity as SiemEvent['severity'],
        description: f.description,
        source: 'ai_sentinel',
        status: 'logged',
      });
    }

    setScanning(false);
    setScanStatus('');
    setScanProgress(0);
    load();
  };

  const releaseUser = async (id: string) => {
    await supabase.from('isolated_users').update({ status: 'released', released_at: new Date().toISOString() }).eq('id', id);
    load();
  };

  return (
    <>
      <PageHeader title="Agentic AI Security Scanner" subtitle="Autonomous AI that scans for threats, isolates suspicious users, and takes rapid action." action={
        <button onClick={runScan} disabled={scanning} className="flex items-center gap-2 rounded-xl bg-[#0d7770] px-4 py-2.5 text-xs font-semibold text-white hover:bg-[#0a6359] disabled:opacity-60">
          {scanning ? <Loader2 size={15} className="animate-spin" /> : <Scan size={15} />} {scanning ? 'Scanning...' : 'Run full scan'}
        </button>
      } />

      {scanning && (
        <Card className="mb-6 p-6">
          <div className="flex items-center gap-3">
            <div className="flex h-12 w-12 items-center justify-center rounded-xl bg-[#e0f3ed] text-[#0d7770]">
              <Cpu size={24} className="animate-pulse" />
            </div>
            <div className="flex-1">
              <p className="text-sm font-semibold">{scanStatus}</p>
              <div className="mt-2 h-2 w-full overflow-hidden rounded-full bg-[#e1e9e9]">
                <div className="h-full rounded-full bg-[#0d7770] transition-all duration-500" style={{ width: `${scanProgress}%` }} />
              </div>
            </div>
            <span className="text-sm font-bold text-[#0d7770]">{scanProgress}%</span>
          </div>
        </Card>
      )}

      <div className="mb-6 grid gap-4 sm:grid-cols-2 xl:grid-cols-4">
        <StatCard label="Users isolated" value={String(isolated.length)} change={isolated.length > 0 ? 'alert' : 'secure'} trend={isolated.length > 0 ? 'up' : 'down'} icon={<Ban size={18} />} tint="red" />
        <StatCard label="Scans run" value={String(scans.length)} change="total" trend="up" icon={<Scan size={18} />} tint="blue" />
        <StatCard label="Last scan anomalies" value={scans[0] ? String(scans[0].anomalies_found) : '0'} change={scans[0] && scans[0].anomalies_found > 0 ? 'alert' : 'ok'} trend={scans[0] && scans[0].anomalies_found > 0 ? 'up' : 'down'} icon={<AlertTriangle size={18} />} tint="orange" />
        <StatCard label="Platform integrity" value="94%" change="healthy" trend="up" icon={<ShieldCheck size={18} />} tint="teal" />
      </div>

      <div className="grid gap-5 lg:grid-cols-2">
        <Card>
          <SectionHeader title="Isolated users" subtitle="Users auto-isolated by the AI sentinel" />
          {loading ? <Spinner /> : isolated.length === 0 ? (
            <EmptyState icon={<ShieldCheck size={24} />} title="No isolated users" subtitle="All users are in good standing." />
          ) : (
            <div className="divide-y divide-[#edf1f1]">
              {isolated.map((u) => (
                <div key={u.id} className="px-5 py-4 sm:px-6">
                  <div className="flex items-start justify-between gap-3">
                    <div className="flex items-start gap-3">
                      <div className="flex h-10 w-10 shrink-0 items-center justify-center rounded-full bg-red-50 text-red-600"><Ban size={18} /></div>
                      <div>
                        <p className="text-sm font-semibold">{u.user_name}</p>
                        <p className="mt-0.5 text-xs text-[#587478]">{u.reason}</p>
                        <div className="mt-1 flex items-center gap-2 text-[10px] text-[#9aabad]">
                          <span>{formatRelative(u.isolated_at)}</span>
                          <span>· by {u.isolated_by === 'ai' ? 'AI Sentinel' : 'Admin'}</span>
                          <span className={`rounded-full px-1.5 py-0.5 font-bold uppercase ${SEVERITY_COLORS[u.severity]}`}>{u.severity}</span>
                        </div>
                      </div>
                    </div>
                    <button onClick={() => releaseUser(u.id)} className="shrink-0 rounded-lg bg-[#e0f3ed] px-3 py-1.5 text-[10px] font-semibold text-[#118370] hover:bg-[#c8e4dc]">Release</button>
                  </div>
                </div>
              ))}
            </div>
          )}
        </Card>

        <Card>
          <SectionHeader title="Recent scans" subtitle="AI security scan history" />
          {loading ? <Spinner /> : scans.length === 0 ? (
            <EmptyState icon={<Scan size={24} />} title="No scans yet" subtitle="Run a full scan to see results here." />
          ) : (
            <div className="divide-y divide-[#edf1f1]">
              {scans.map((s) => (
                <div key={s.id} className="px-5 py-4 sm:px-6">
                  <div className="flex items-start justify-between">
                    <div className="flex items-start gap-3">
                      <div className={`flex h-10 w-10 items-center justify-center rounded-full ${s.status === 'completed' ? 'bg-[#e0f3ed] text-[#118370]' : 'bg-[#fff8e0] text-[#b8860b]'}`}>
                        {s.status === 'completed' ? <CheckCircle2 size={18} /> : <Loader2 size={18} className="animate-spin" />}
                      </div>
                      <div>
                        <p className="text-sm font-semibold capitalize">{s.scan_type.replace(/_/g, ' ')}</p>
                        <p className="mt-0.5 text-xs text-[#587478]">{s.anomalies_found} anomalies · {s.actions_taken} actions · {s.users_isolated} isolated</p>
                        <p className="mt-0.5 text-[10px] text-[#9aabad]">{formatRelative(s.started_at)}</p>
                      </div>
                    </div>
                    <span className={`rounded-full px-2 py-0.5 text-[10px] font-semibold capitalize ${s.status === 'completed' ? 'bg-[#e0f3ed] text-[#118370]' : 'bg-[#fff8e0] text-[#b8860b]'}`}>{s.status}</span>
                  </div>
                  {s.ai_summary && (
                    <div className="mt-2 flex items-start gap-2 rounded-lg bg-[#f7f9f8] p-2.5 text-[11px] text-[#587478]">
                      <div className="flex h-5 w-5 shrink-0 items-center justify-center rounded bg-[#0d7770] text-[8px] font-bold text-white">AI</div>
                      {s.ai_summary}
                    </div>
                  )}
                </div>
              ))}
            </div>
          )}
        </Card>
      </div>

      {scans[0]?.findings && scans[0].findings.length > 0 && (
        <Card className="mt-5">
          <SectionHeader title="Latest scan findings" subtitle="Detailed AI analysis from the most recent scan" />
          <div className="divide-y divide-[#edf1f1]">
            {scans[0].findings.map((f, i) => (
              <div key={i} className="px-5 py-4 sm:px-6">
                <div className="flex items-start justify-between gap-3">
                  <div className="flex items-start gap-3">
                    <div className={`flex h-8 w-8 shrink-0 items-center justify-center rounded-full ${SEVERITY_COLORS[f.severity] ?? SEVERITY_COLORS.low}`}>
                      <AlertTriangle size={15} />
                    </div>
                    <div>
                      <p className="text-sm font-semibold">{f.title}</p>
                      <p className="mt-0.5 text-xs text-[#587478]">{f.description}</p>
                      <p className="mt-1 flex items-center gap-1.5 text-[11px] font-semibold text-[#0d7770]"><Zap size={12} /> {f.action}</p>
                    </div>
                  </div>
                  <span className={`shrink-0 rounded-full px-2 py-0.5 text-[10px] font-bold uppercase ${SEVERITY_COLORS[f.severity] ?? SEVERITY_COLORS.low}`}>{f.severity}</span>
                </div>
              </div>
            ))}
          </div>
        </Card>
      )}
    </>
  );
}
